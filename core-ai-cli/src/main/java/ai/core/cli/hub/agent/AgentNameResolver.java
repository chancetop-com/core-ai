package ai.core.cli.hub.agent;

import ai.core.api.server.agenthub.AgentHubSummary;
import ai.core.cli.hub.HubCliError;
import ai.core.cli.hub.HubExitCodes;

import java.util.List;

/**
 * Resolves the {@code <id | name>} argument of the {@code agent} subcommands.
 * <p>
 * Ids go straight to the server: a value of a shape the server hands out as an id skips the lookup,
 * and anything else without a visible name match is still passed through — it can be a valid id this
 * fast path does not enumerate ({@code default-assistant}, {@code assistant:<userId>}), and the
 * server owns that 404. A name that matches several agents is a usage error listing the candidates —
 * the caller has to disambiguate by id (agent names are only unique per owner).
 *
 * @author stephen
 */
public class AgentNameResolver {
    private static final int UUID_LENGTH = 36;
    private static final int LEGACY_ID_LENGTH = 24;

    private final AgentHubClient client;

    public AgentNameResolver(AgentHubClient client) {
        this.client = client;
    }

    public String resolve(String idOrName) {
        if (idOrName == null || idOrName.isBlank()) throw new HubCliError(HubExitCodes.USAGE, "agent id or name required");
        if (looksLikeId(idOrName)) return idOrName;
        var candidates = client.lookup(idOrName).candidates;
        if (candidates == null || candidates.isEmpty()) {
            // no visible agent is named that — pass it through as an id and let the server resolve or 404
            return idOrName;
        }
        if (candidates.size() > 1) {
            throw new HubCliError(HubExitCodes.USAGE, ambiguousMessage(idOrName, candidates));
        }
        return candidates.get(0).id;
    }

    private String ambiguousMessage(String name, List<AgentHubSummary> candidates) {
        var message = new StringBuilder(256).append("more than one agent is named '").append(name).append("', use an id:\n");
        for (var candidate : candidates) {
            message.append("  ").append(candidate.id).append("  ").append(candidate.name);
            if (candidate.ownerIsMe != null && candidate.ownerIsMe) message.append("  (mine)");
            message.append('\n');
        }
        return message.toString();
    }

    /** The id shapes recognized without a lookup: a dashed uuid as generated by the server, or a 24-hex object id. */
    private boolean looksLikeId(String value) {
        if (value.length() == UUID_LENGTH) return isDashedUuid(value);
        return value.length() == LEGACY_ID_LENGTH && isHex(value, 0, value.length());
    }

    private boolean isDashedUuid(String value) {
        for (int index = 0; index < value.length(); index++) {
            char current = value.charAt(index);
            if (index == 8 || index == 13 || index == 18 || index == 23) {
                if (current != '-') return false;
            } else if (Character.digit(current, 16) < 0) {
                return false;
            }
        }
        return true;
    }

    private boolean isHex(String value, int from, int to) {
        for (int index = from; index < to; index++) {
            if (Character.digit(value.charAt(index), 16) < 0) return false;
        }
        return true;
    }
}
